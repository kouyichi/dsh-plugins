function makeMockCtx() {
  const registrations = [];
  const skills = [];
  const disposers = [];
  const ctx = {
    get(service) {
      if (service === "tools") {
        return {
          register: (def) => { registrations.push(def); return () => {}; },
          guard: () => () => {},
        };
      }
      if (service === "skills") {
        return { register: (s) => { skills.push(s); return () => {}; } };
      }
      return null;
    },
    interval() { return () => {}; },
    effect(fn) { if (typeof fn === "function") { const r = fn(); if (typeof r === "function") disposers.push(r); } },
    on() { return () => {}; },
    logger: { info() {}, warn() {}, error() {} },
  };
  return { ctx, registrations, skills, disposers };
}

async function verifyPluginDir(dir) {
  const root = resolve(String(dir));
  const indexPath = join(root, "index.js");
  if (!existsSync(indexPath)) throw new Error(`目录没有 index.js: ${root}`);
  const problems = [];
  const { ctx, registrations, skills } = makeMockCtx();
  let mod;
  try {
    mod = await import(pathToFileURL(indexPath).href);
  } catch (err) {
    return { ok: false, problems: [`import 失败: ${err.message}`], tools: 0, skills: 0 };
  }
  if (typeof mod.name !== "string" || !mod.name) problems.push("缺少 name 导出");
  if (!Array.isArray(mod.inject) || !mod.inject.includes("tools")) problems.push("inject 必须包含 'tools'");
  if (typeof mod.apply !== "function") problems.push("缺少 apply(ctx) 导出");
  if (problems.length === 0) {
    try { mod.apply(ctx); } catch (err) { problems.push(`apply(ctx) 抛错: ${err.message}`); }
  }
  for (const t of registrations) {
    const label = t.name || "<unnamed>";
    if (!t.description) problems.push(`工具 ${label}: 缺 description`);
    if (!t.parameters || t.parameters.type !== "object") problems.push(`工具 ${label}: parameters 必须是 object schema`);
    if (!t.output || !t.output.schema) problems.push(`工具 ${label}: 缺 output.schema（rc.6 强制）`);
    if (typeof t.output?.render !== "function") problems.push(`工具 ${label}: output.render 必须是函数`);
    if (typeof t.execute !== "function") problems.push(`工具 ${label}: 缺 execute`);
    if (t.presentCall !== undefined && typeof t.presentCall !== "function") problems.push(`工具 ${label}: presentCall 必须是函数`);
  }
  return {
    ok: problems.length === 0,
    plugin: mod.name ?? "?",
    tools: registrations.length,
    skills: skills.length,
    problems,
  };
}

