export function apply(ctx) {
  const tools = ctx.get("tools");
  const disposers = [];

  tools.register({
    name: "scaffold_plugin",
    description: "生成一个 rc.6 规范的 dsh 插件骨架：package.json + index.js（含示例工具，output:{schema,render} 契约）+ verify.mjs（mock-ctx 注册检查脚本）+ README.md。用于快速开始插件开发。",
    parameters: {
      type: "object",
      properties: {
        name: { type: "string", description: "插件名（小写连字符，必填）" },
        dir: { type: "string", description: "可选：生成目录（默认当前工作目录，生成 <name>/ 子目录）" },
        description: { type: "string", description: "可选：一句话描述（写入 package.json/README）" },
        with_verify: { type: "boolean", description: "是否生成 verify.mjs（默认 true）" },
      },
      required: ["name"],
    },
    output: { schema: { type: "string" }, render: (_args, value) => [{ type: "text", text: String(value) }] },
    async execute(args) {
      const target = scaffoldPlugin({ name: args.name, dir: args.dir, description: args.description, withVerify: args.with_verify });
      const files = readdirSync(target).sort();
      return `已生成插件骨架 ${basename(target)} → ${target}\n文件: ${files.join(", ")}\n\n下一步：\n1. 编辑 index.js 添加你的工具（保持 output:{schema,render} 契约）\n2. node verify.mjs ${target} 做注册检查\n3. 挂载：链接到 ~/.dsh/plugins/ + 家级 cordis.patch.yml insert 一行（或 profile 依赖）\n4. 用 compat_check 检查 rc.6 兼容性`;
    },
    presentCall: (args) => present("脚手架：生成插件", args?.name || ""),
  });

  tools.register({
    name: "verify_plugin",
    description: "验证一个 dsh 插件目录的 rc.6 注册契约：mock ctx 加载 index.js，逐工具检查 name/description/parameters/output.{schema,render}/execute/presentCall，以及 name/inject 导出。返回检查报告。",
    parameters: {
      type: "object",
      properties: { dir: { type: "string", description: "插件目录（含 index.js 与 package.json）" } },
      required: ["dir"],
    },
    output: { schema: { type: "string" }, render: (_args, value) => [{ type: "text", text: String(value) }] },
    async execute(args) {
      const r = await verifyPluginDir(args.dir);
      const lines = [];
      lines.push(`插件 ${r.plugin}：注册 ${r.tools} 个工具 / ${r.skills} 个技能`);
      if (r.ok) {
        lines.push("✅ 全部通过 rc.6 注册契约检查");
      } else {
        lines.push(`❌ ${r.problems.length} 个问题:`);
        for (const p of r.problems) lines.push(`- ${p}`);
      }
      return lines.join("\n");
    },
    presentCall: (args) => present("脚手架：验证插件", args?.dir || ""),
  });

  tools.register({
    name: "compat_check",
    description: "检查 dsh 插件目录与当前安装 dsh 版本的兼容性：package.json 规范性（ESM/main）、index.js 存在性、rc.6 已知坑扫描（presentResult 失效 API、ctx.interval 缺 timer inject、tools.register 缺 output）。",
    parameters: {
      type: "object",
      properties: { dir: { type: "string", description: "插件目录（默认当前工作目录）" } },
      required: [],
    },
    output: { schema: { type: "string" }, render: (_args, value) => [{ type: "text", text: String(value) }] },
    async execute(args) {
      const r = compatCheck(args.dir || ".");
      return r.text;
    },
    presentCall: () => present("脚手架：兼容性检查", "compat_check"),
  });

  const skillsSvc = ctx.get("skills");
  if (skillsSvc && typeof skillsSvc.register === "function") {
    disposers.push(skillsSvc.register({
      name: "scaffold",
      description: "dsh 插件开发工具链：scaffold_plugin 生成 rc.6 骨架、verify_plugin mock-ctx 注册验证、compat_check 兼容性扫描。",
      whenToUse: "当要开发新 dsh 插件、验证插件能否加载、或排查插件 API 兼容性问题时使用。",
      source: "custom",
      content: [
        "## 用途",
        "",
        "dsh 插件开发三件套：",
        "- `scaffold_plugin name=xxx`：生成 rc.6 规范骨架（index.js + package.json + verify.mjs + README）",
        "- `verify_plugin dir=<目录>`：mock-ctx 加载并逐工具检查注册契约（output:{schema,render} 等）",
        "- `compat_check dir=<目录>`：扫描 rc.6 已知坑（presentResult、timer inject、缺 output）",
        "",
        "## rc.6 关键契约（写插件必守）",
        "",
        "- `tools.register()` 必须带 `output: {schema, render}`（旧 presentResult 已失效）",
        "- `ctx.interval()` 的 inject 必须含 `\"timer\"`，否则定时器永不触发",
        "- 子代理 `run.result.output` 是 blocks 数组不是字符串（取 text 块拼接）",
        "- 本机无 bubblewrap：新 profile 必须在 cordis.patch.yml 覆盖 sandbox-policy(danger-full-access) + approval(never)",
        "- `presentCall` 返回 `{card:'generic', title, content:[{type:'text',text}]}`",
        "",
        "## 挂载插件",
        "",
        "1. 链接到 `~/.dsh/plugins/<name>`（或 profile plugins/ 目录）",
        "2. 家级：`~/.dsh/cordis.patch.yml` insert 列表加 `- id: <name> / name: <name>`",
        "3. profile 级：package.json dependencies 加 `file:` 依赖 + pnpm install",
        "",
        "## 注意",
        "",
        "- 生成骨架后用 `node verify.mjs <目录>` 即可独立验证（不依赖 dsh 运行）",
        "- 官方 API 仍在 breaking change 期：插件应记录目标 rc 版本",
      ],
    }));
  }

  ctx.effect(() => () => {
    for (const d of disposers) { try { d(); } catch { /* ignore */ } }
  });
}
