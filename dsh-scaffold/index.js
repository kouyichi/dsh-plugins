/**
 * dsh-scaffold — plugin development toolchain for DeepSeek Harness.
 *
 * Ecosystem gap: dsh is in a fast-breaking rc phase (rc.6 already changed the
 * tool-registration API) and NO scaffolding / verification / compatibility
 * tooling exists yet (only a few skill-level repos, ≤21★). This plugin closes
 * that gap with three tools:
 *
 *   scaffold_plugin — generate an rc.6-compliant plugin skeleton
 *                     (package.json + index.js with defineTool-style tools +
 *                      mock-ctx verify script + README)
 *   verify_plugin   — load a plugin's index.js with a mock ctx and prove that
 *                     every tool registration satisfies the rc.6 contract
 *                     (output.{schema,render} present, presentCall shape,
 *                     name/inject exports, timer inject for ctx.interval)
 *   compat_check    — compare a plugin directory against the installed dsh
 *                     version and scan for known rc.6 API pitfalls
 *                     (tools.register without output, presentResult, ...)
 *
 * @module dsh-scaffold
 */

