/** Strip comments and quoted strings so naive pattern scans don't false-positive on docs. */
function stripStringsAndComments(text) {
  let out = "";
  let i = 0;
  const n = text.length;
  while (i < n) {
    const c = text[i];
    if (c === "/" && text[i + 1] === "/") {
      while (i < n && text[i] !== "\n") i++;
    } else if (c === "/" && text[i + 1] === "*") {
      i += 2;
      while (i < n && !(text[i] === "*" && text[i + 1] === "/")) i++;
      i += 2;
    } else if (c === '"' || c === "'" || c === "`") {
      const q = c;
      i++;
      while (i < n && text[i] !== q) {
        if (text[i] === "\\") i++;
        i++;
      }
      i++;
      out += " ";
    } else {
      out += c;
      i++;
    }
  }
  return out;
}

function scanPitfalls(root) {
  const found = [];
  const walk = (d) => {
    let entries;
    try { entries = readdirSync(d, { withFileTypes: true }); } catch { return; }
    for (const e of entries) {
      if (e.name === "node_modules" || e.name === ".git") continue;
      const p = join(d, e.name);
      if (e.isDirectory()) { walk(p); continue; }
      if (!/\.(js|mjs|ts)$/.test(e.name)) continue;
      let raw;
      try { raw = readFileSync(p, "utf8"); } catch { continue; }
      const text = stripStringsAndComments(raw);
      if (/presentResult/.test(text)) found.push({ file: p, issue: "使用已失效的 presentResult（rc.6 改为 output.render）" });
      // ctx.interval without timer in inject
      if (/ctx\.interval/.test(text) && !/inject\s*=\s*\[[^\]]*timer/.test(text)) {
        found.push({ file: p, issue: "ctx.interval 但 inject 未包含 \"timer\"（interval 将永不触发）" });
      }
      // tools.register without output block (rough heuristic)
      if (/tools\.register\s*\(/.test(text) && !/output\s*:/.test(text)) {
        found.push({ file: p, issue: "tools.register 未声明 output（rc.6 强制 {schema, render}）" });
      }
    }
  };
  walk(root);
  return found;
}

function compatCheck(dir) {
  const root = resolve(String(dir || "."));
  const dshVer = installedDshVersion();
  const lines = [`dsh 安装版本: ${dshVer}`, `检查目录: ${root}`];
  const issues = [];
  // package.json sanity
  const pkgPath = join(root, "package.json");
  if (existsSync(pkgPath)) {
    try {
      const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
      if (pkg.type !== "module") issues.push("package.json 缺 \"type\": \"module\"（插件须为 ESM）");
      if (!pkg.main || !existsSync(join(root, pkg.main))) issues.push(`package.json main 指向不存在的文件: ${pkg.main}`);
    } catch { issues.push("package.json 解析失败"); }
  } else {
    issues.push("目录没有 package.json");
  }
  if (!existsSync(join(root, "index.js"))) issues.push("目录没有 index.js");
  const pitfalls = scanPitfalls(root);
  for (const p of pitfalls) issues.push(`${p.file.replace(root, ".")}: ${p.issue}`);
  lines.push(`发现问题: ${issues.length}`);
  for (const i of issues) lines.push(`- ${i}`);
  const v = dshVer.match(/rc\.(\d+)/);
  lines.push(`提示: 官方声明 rc 阶段会有 breaking changes，插件应跟随安装版本实测（建议跑 verify_plugin）`);
  return { dshVersion: dshVer, issues, ok: issues.length === 0, text: lines.join("\n") };
}

