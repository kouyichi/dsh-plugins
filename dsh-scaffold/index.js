const present = (title, text) => ({ card: "generic", title, content: [{ type: "text", text: String(text) }] });
const cap = (s, n) => { s = String(s ?? ""); return s.length > n ? s.slice(0, n) + "…" : s; };

function slugify(s) {
  return String(s || "").trim().toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 48);
}

/** Resolve the installed @deepseek-ai/dsh version. */
export function installedDshVersion() {
  // 1) the running CLI entry's package.json (argv[1] is the dsh launcher script)
  try {
    const entry = resolve(process.argv[1] || "");
    let dir = dirname(entry);
    for (let i = 0; i < 8; i++) {
      const pkg = join(dir, "package.json");
      if (existsSync(pkg)) {
        const j = JSON.parse(readFileSync(pkg, "utf8"));
        if (j.name === "@deepseek-ai/dsh" || j.name === "dsh") return j.version;
      }
      const up = dirname(dir);
      if (up === dir) break;
      dir = up;
    }
  } catch { /* fall through */ }
  // 2) `dsh --version` on PATH (nvm bin first)
  try {
    const bin = "/root/.nvm/versions/node/v22.22.2/bin";
    const out = execFileSync(join(bin, "dsh"), ["--version"], { encoding: "utf8", timeout: 5000 }).trim();
    if (out) return out;
  } catch { /* fall through */ }
  return "unknown";
}

